import type { CardSet, ExtraZombie, RushZombie, SpawnCounts, ZombieCard, ZombieType } from '../game/types';

// Transcribed from the physical cards; ids follow the numbers printed on them.
// Counts are in Danger Level order: blue, yellow, orange, red (the cards print them top-down, red first).

const spawn = (setId: string, id: string, zombie: ZombieType, counts: SpawnCounts): ZombieCard => ({
  id: `${setId}-${id}`,
  setId,
  kind: 'spawn',
  zombie,
  counts,
});

const rush = (setId: string, id: string, zombie: RushZombie, counts: SpawnCounts): ZombieCard => ({
  id: `${setId}-${id}`,
  setId,
  kind: 'rush',
  zombie,
  counts,
});

const extra = (setId: string, id: string, zombie: ExtraZombie): ZombieCard => ({
  id: `${setId}-${id}`,
  setId,
  kind: 'extra',
  zombie,
});

const shooter = (card: ZombieCard): ZombieCard =>
  card.kind === 'spawn' || card.kind === 'rush' ? { ...card, shooter: true } : card;

const special = (setId: string, id: string, kind: 'trejo' | 'trejoRush' | 'spam'): ZombieCard => ({
  id: `${setId}-${id}`,
  setId,
  kind,
});

